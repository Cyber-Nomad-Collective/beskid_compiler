#[cfg(test)]
mod tests {
    use super::*;

    /// Fails when a grammar rule has no words: add the rule to [`RULE_WORDS`].
    #[test]
    fn every_grammar_rule_has_words() {
        let missing: Vec<String> = Rule::all_rules()
            .iter()
            .filter(|rule| !RULE_WORDS.iter().any(|(candidate, _)| candidate == *rule))
            .map(|rule| format!("{rule:?}"))
            .collect();
        assert!(missing.is_empty(), "grammar rules without words in rule_words.rs: {missing:?}");
    }

    #[test]
    fn every_rule_has_exactly_one_entry() {
        let mut seen = std::collections::HashSet::new();
        for (rule, _) in RULE_WORDS {
            assert!(seen.insert(*rule), "{rule:?} has two entries");
        }
        // `EOI` is a rule variant that `all_rules` leaves out.
        for (rule, _) in RULE_WORDS {
            assert!(*rule == Rule::EOI || Rule::all_rules().contains(rule), "{rule:?} is not a grammar rule");
        }
    }

    #[test]
    fn words_never_spell_a_rule_name() {
        for (rule, words) in RULE_WORDS {
            let text = words.render();
            let name = format!("{rule:?}");
            assert!(!text.is_empty(), "{name} has empty words");
            if name.len() > 4 {
                assert!(!text.contains(&name), "{name} words repeat the rule name: {text}");
            }
        }
    }
}
