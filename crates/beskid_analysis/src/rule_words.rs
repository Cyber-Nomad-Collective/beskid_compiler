//! Grammar rules of `beskid.pest` in words, for parse diagnostics.
//!
//! Every [`Rule`] the grammar generates (silent rules included) has exactly one entry in [`RULE_WORDS`]; the test at the
//! bottom fails when a rule is added to the grammar without one. Diagnostics never print a rule
//! name: they print the words from this table.
//!
//! An entry says how to name the rule when the parser expected it:
//! - [`Words::Token`]: the rule matches one fixed spelling, shown in backticks (`mut`).
//! - [`Words::Thing`]: something a person types as one unit ("a name", "a type").
//! - [`Words::Construct`]: a larger construct ("a host declaration"). The parser reports the tokens
//!   inside a construct, so a construct is named as expected only when nothing more precise is known.

use crate::parser::Rule;

/// How a rule reads in a diagnostic.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Words {
    Token(&'static str),
    Thing(&'static str),
    Construct(&'static str),
}

impl Words {
    /// The words as they appear in a message: a token in backticks, other words as written.
    pub fn render(self) -> String {
        match self {
            Words::Token(text) => format!("`{text}`"),
            Words::Thing(text) | Words::Construct(text) => text.to_string(),
        }
    }
}

/// The words for `rule`.
pub fn rule_words(rule: Rule) -> Words {
    RULE_WORDS
        .iter()
        .find(|(candidate, _)| *candidate == rule)
        .map(|(_, words)| *words)
        .unwrap_or(Words::Construct("valid syntax"))
}

