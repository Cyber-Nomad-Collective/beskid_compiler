//! The checked-in compiler-sdk surfaces that mirror `beskid_analysis`, and their freshness check.
//!
//! `corelib/packages/compiler-sdk/regen_mod_sdk_surfaces.sh` writes every surface listed here.
//! The tests in this module compare the checked-in files with a fresh generation, so a Rust
//! change that the Corelib mirror does not follow fails the workspace tests.

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

use crate::{GenError, GenOptions, format_bd, generate_from_paths};

/// Rust sources of the `Beskid.Compiler.Diagnostics` mirror, relative to the compiler workspace root.
pub const DIAGNOSTICS_SDK_SOURCES: &[&str] = &[
    "crates/beskid_analysis/src/analysis/diagnostic_kinds.rs",
    "crates/beskid_analysis/src/analysis/diagnostics/semantic.rs",
];

/// Rust items of [`DIAGNOSTICS_SDK_SOURCES`] that the diagnostics mirror carries.
pub const DIAGNOSTICS_SDK_ITEMS: &[&str] = &["SemanticIssueKind", "Severity"];

/// Path of the compiler-sdk `Beskid` source directory, relative to the compiler workspace root.
pub const COMPILER_SDK_BESKID_DIR: &str = "corelib/packages/compiler-sdk/src/Beskid";

const DIAGNOSTICS_PRELUDE: &str = "\
// CHECKED IN: regenerated by packages/compiler-sdk/regen_mod_sdk_surfaces.sh
// Rust sources in beskid_analysis are authoritative; do not edit this file by hand.

/// Structural placeholder emitted by beskid_ast_reflect_gen for diagnostic payload fields
/// whose Rust types are not yet mapped to concrete Beskid types.
pub type ReflectStub { }

";

const DIAGNOSTICS_FACADE: &str = "
// Facade ----------------------------------------------------------------------
// Construction and reporting of compiler-native diagnostics from mod analyzers.

// Diagnostics facade contract version aligned with platform-spec Beskid.Compiler.Diagnostics hub.
pub string DiagnosticsFacadeVersion()
{
    return \"0.2.0\";
}
";

/// `Beskid/Compiler/Diagnostics.bd` as the generator writes it: the `SemanticIssueKind` and
/// `Severity` mirrors of [`DIAGNOSTICS_SDK_SOURCES`] and the facade, printed by the formatter.
pub fn emit_diagnostics_sdk(compiler_workspace_root: &Path) -> Result<String, GenError> {
    let paths: Vec<PathBuf> = DIAGNOSTICS_SDK_SOURCES.iter().map(|rel| compiler_workspace_root.join(rel)).collect();
    let options = GenOptions {
        only_annotated: false,
        emit_banner: false,
        emit_reflect_stub: false,
        item_allowlist: Some(DIAGNOSTICS_SDK_ITEMS.iter().map(|s| (*s).to_string()).collect::<BTreeSet<_>>()),
    };
    let mirrors = generate_from_paths(&paths, &options)?;
    let text = format!("{DIAGNOSTICS_PRELUDE}{mirrors}{DIAGNOSTICS_FACADE}");
    Ok(format_bd(Path::new("Beskid/Compiler/Diagnostics.bd"), &text)?)
}

#[cfg(test)]
mod tests {
    use std::fs;
    use std::path::{Path, PathBuf};

    use super::{COMPILER_SDK_BESKID_DIR, emit_diagnostics_sdk};
    use crate::syntax_nodes::{emit_syntax_sdk, inventory_syntax_type_names};
    use crate::syntax_traversal::emit_query_facade_body;

    const REGEN: &str = "run `bash corelib/packages/compiler-sdk/regen_mod_sdk_surfaces.sh` from the compiler workspace \
                         root and commit the Corelib change";

    fn workspace_root() -> PathBuf {
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..")
    }

    fn checked_in(rel: &str) -> String {
        let path = workspace_root().join(COMPILER_SDK_BESKID_DIR).join(rel);
        fs::read_to_string(&path).unwrap_or_else(|error| panic!("read checked-in {}: {error}", path.display()))
    }

    /// Every file under `dir`, as paths relative to `dir`.
    fn files_under(dir: &Path) -> Vec<PathBuf> {
        let mut out = Vec::new();
        let mut pending = vec![dir.to_path_buf()];
        while let Some(next) = pending.pop() {
            for entry in fs::read_dir(&next).unwrap_or_else(|error| panic!("list {}: {error}", next.display())) {
                let path = entry.expect("directory entry").path();
                if path.is_dir() {
                    pending.push(path);
                } else {
                    out.push(path.strip_prefix(dir).expect("under dir").to_path_buf());
                }
            }
        }
        out.sort();
        out
    }

    #[test]
    fn checked_in_diagnostics_surface_matches_the_rust_diagnostic_kinds() {
        let generated = emit_diagnostics_sdk(&workspace_root()).expect("generate the diagnostics surface");
        assert!(
            checked_in("Compiler/Diagnostics.bd") == generated,
            "corelib compiler-sdk Beskid/Compiler/Diagnostics.bd is stale against beskid_analysis \
             SemanticIssueKind/Severity; {REGEN}"
        );
    }

    #[test]
    fn checked_in_query_facade_matches_the_syntax_inventory() {
        let analysis = workspace_root().join("crates/beskid_analysis/src");
        let inventory = inventory_syntax_type_names(&analysis).expect("syntax inventory");
        let generated =
            crate::format_bd(Path::new("Beskid/Compiler/Query.bd"), &emit_query_facade_body(&inventory)).expect("format");
        assert!(
            checked_in("Compiler/Query.bd") == generated,
            "corelib compiler-sdk Beskid/Compiler/Query.bd is stale against the beskid_analysis syntax inventory; {REGEN}"
        );
    }

    #[test]
    fn checked_in_syntax_surface_matches_the_syntax_nodes() {
        let analysis = workspace_root().join("crates/beskid_analysis/src");
        let unique = std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).unwrap().as_nanos();
        let root = std::env::temp_dir().join(format!("beskid-sdk-fresh-{}-{unique}", std::process::id()));
        struct Cleanup(PathBuf);
        impl Drop for Cleanup {
            fn drop(&mut self) {
                let _ = fs::remove_dir_all(&self.0);
            }
        }
        let _cleanup = Cleanup(root.clone());
        emit_syntax_sdk(&root, &analysis).expect("generate the syntax surface");
        let checked_in_root = workspace_root().join(COMPILER_SDK_BESKID_DIR);
        let generated = files_under(&root.join("Syntax"));
        let committed = files_under(&checked_in_root.join("Syntax"));
        assert_eq!(committed, generated, "corelib compiler-sdk Beskid/Syntax holds other files than the generator writes; {REGEN}");
        let stale: Vec<_> = std::iter::once(PathBuf::from("Syntax.bd"))
            .chain(generated.iter().map(|rel| Path::new("Syntax").join(rel)))
            .filter(|rel| fs::read(root.join(rel)).ok() != fs::read(checked_in_root.join(rel)).ok())
            .collect();
        assert!(stale.is_empty(), "stale corelib compiler-sdk syntax surfaces {stale:?}; {REGEN}");
    }
}
